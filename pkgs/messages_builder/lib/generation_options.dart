import 'dart:io';

import 'package:collection/collection.dart';
import 'package:yaml/yaml.dart';

/// Options for the message data file and code generation.
class GenerationOptions {
  /// The data file serialization, either json or (TBD) binary.
  final SerializationType serialization;

  /// The data file deserialization, either through browser functionalities or
  /// dart native code.
  final DeserializationType deserialization;

  /// The header to add to all generated files, for example for licensing.
  final String header;

  /// The origin of the algorithm for determining which plural case to use.
  final PluralSelectorType pluralSelector;

  /// The asset loading style (flutter, dart, or manual).
  final AssetLoadingStyle assetLoadingStyle;

  /// Where the arb files are located.
  final Directory arbFolder;

  /// Where to write the message data files to.
  final Directory messageFolder;

  final Directory codeOutputFolder;

  final String packageName;

  static const _headerKey = 'header';
  static const _pluralSelectorKey = 'plural_selector';
  static const _arbInputFolderKey = 'arb_input_folder';
  static const _messageOutputFolderKey = 'message_output_folder';
  static const _codeOutputFolderKey = 'code_output_folder';
  static const _assetLoadingStyleKey = 'asset_loading_style';

  static List<String> get validKeys => [
    _pluralSelectorKey,
    _headerKey,
    _arbInputFolderKey,
    _messageOutputFolderKey,
    _codeOutputFolderKey,
    _assetLoadingStyleKey,
  ];

  GenerationOptions({
    required this.serialization,
    required this.deserialization,
    required this.header,
    required this.pluralSelector,
    required this.assetLoadingStyle,
    required this.packageName,
    required this.arbFolder,
    required this.messageFolder,
    required this.codeOutputFolder,
  });

  static Future<GenerationOptions> fromPubspec(String pubspecData) async {
    final pubspec = loadYaml(pubspecData) as YamlMap;
    final packageOptions = pubspec['package_options'] as YamlMap?;
    final messagesOptions = packageOptions?['messages_builder'] as YamlMap?;
    final illegalKey = messagesOptions?.keys.firstWhereOrNull(
      (key) => !validKeys.contains(key),
    );
    if (illegalKey != null) {
      throw ArgumentError(
        'The message options contain the illegal key $illegalKey',
      );
    }
    final header = messagesOptions?[_headerKey];
    final generationOptions = GenerationOptions(
      serialization: SerializationType.json,
      deserialization: DeserializationType.web,
      header: header != null
          ? '$header\nGenerated by package:messages_builder.'
          : 'Generated by package:messages_builder.',
      pluralSelector: _pluralSelector(messagesOptions),
      assetLoadingStyle: _assetLoadingStyle(pubspec, messagesOptions),
      packageName: pubspec['name'] as String,
      arbFolder: Directory(
        messagesOptions?[_arbInputFolderKey] as String? ?? 'assets/l10n/',
      ),
      messageFolder: Directory(
        messagesOptions?[_messageOutputFolderKey] as String? ?? 'assets/',
      ),
      codeOutputFolder: Directory(
        messagesOptions?[_codeOutputFolderKey] as String? ?? 'lib/src/',
      ),
    );
    return generationOptions;
  }

  static PluralSelectorType _pluralSelector(YamlMap? messagesOptions) {
    final pluralSelectorString =
        messagesOptions?[_pluralSelectorKey] as String?;
    return pluralSelectorString != null
        ? PluralSelectorType.values
              .where((type) => type.name == pluralSelectorString)
              .first
        : PluralSelectorType.intl;
  }

  static AssetLoadingStyle _assetLoadingStyle(
    YamlMap pubspec,
    YamlMap? messagesOptions,
  ) {
    final styleString = messagesOptions?[_assetLoadingStyleKey] as String?;
    if (styleString != null) {
      final matched = AssetLoadingStyle.values.firstWhereOrNull(
        (type) => type.name == styleString,
      );
      if (matched == null) {
        throw ArgumentError(
          'The message options contain the illegal asset_loading_style value '
          '"$styleString". Valid values are: flutter, dart, manual.',
        );
      }
      return matched;
    }
    return _isFlutterApp(pubspec)
        ? AssetLoadingStyle.flutter
        : AssetLoadingStyle.dart;
  }

  static bool _isFlutterApp(YamlMap pubspec) {
    if (pubspec.containsKey('flutter')) return true;
    final dependencies = pubspec['dependencies'];
    if (dependencies is YamlMap && dependencies.containsKey('flutter')) {
      return true;
    }
    final devDependencies = pubspec['dev_dependencies'];
    if (devDependencies is YamlMap && devDependencies.containsKey('flutter')) {
      return true;
    }
    return false;
  }
}

enum SerializationType { json }

enum DeserializationType { web }

/// Asset loading style for generated message code and assets.
enum AssetLoadingStyle { flutter, dart, manual }

typedef TargetEnvironment = AssetLoadingStyle;

/// The origin of the algorithm for determining which plural case to use.
enum PluralSelectorType {
  /// From `package:intl`.
  intl,

  /// From `package:intl4x`.
  intl4x,

  /// A user-specified algorithm.
  custom,
}
